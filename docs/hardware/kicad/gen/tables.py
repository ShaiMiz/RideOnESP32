def write_nets(out, nets, parts):
    by_ref = {p.ref: p for p in parts}
    rows = []
    for n in sorted(nets):
        g, c, fuse = W.net_class(n)
        sheets = sorted({by_ref[r].sheet for r, _, _ in nets[n]})
        pins = ", ".join(f"{r}.{num}" for r, num, _ in sorted(nets[n]) if not r.startswith("#"))
        rows.append([f"`{n}`", g, c, fuse, " ".join(sheets), pins])
    (out / "NETS.md").write_text(HEAD + "# Nets (v0.3)\n\n"
                                 "Every net in the schematic with its default wire gauge, colour and protecting fuse, the sheets it "
                                 "appears on and every pin on it. ESP32 signal names are the constants in include/pins.h.\n\n"
                                 + md_table(["Net", "AWG", "Colour", "Protected by", "Sheets", "Pins"], rows))


