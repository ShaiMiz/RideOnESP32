def endpoint_net(ep, by_ref, syms):
    if ep in W.BUS:
        return W.BUS[ep], None
    ref, pin = ep.split(".", 1)
    part = by_ref[ref]
    sym = syms[part.sym]
    p = sym.pin(pin)
    return part.pins[p.number], (ref, p.number)


def check_and_number_runs(parts, syms):
    by_ref = {p.ref: p for p in parts}
    errors, rows, covered = [], [], set()
    for i, r in enumerate(W.RUNS):
        try:
            na, pa = endpoint_net(r["a"], by_ref, syms)
            nb, pb = endpoint_net(r["b"], by_ref, syms)
        except KeyError as e:
            errors.append(f"run {r['a']} -> {r['b']}: {e}")
            continue
        if na != nb or na is None:
            errors.append(f"run {r['a']} -> {r['b']}: nets differ ({na} vs {nb})")
            continue
        covered |= {pa, pb} - {None}
        g, c, fuse = W.net_class(na)
        gauge = r["gauge"] or g
        ours = {"J9", "J10", "J11", "J12"}
        if (r["route"] == "harness" or {pa and pa[0], pb and pb[0]} & ours) and gauge > 20:
            gauge = 20  # Deutsch DT size-16 contacts take 20-14 AWG, and off-box wires need the strength
        if r["route"] in ("stock",):
            gauge, c = "stock", "stock"
        rows.append(dict(id=f"W{i + 1:03d}", a=r["a"], b=r["b"], net=na, awg=gauge, colour=r["colour"] or c,
                         fuse=fuse, route=r["route"], note=r["note"]))
    # coverage: every connected pin off the interface board needs a wire or a reason
    for p in parts:
        if p.ref.startswith("#") or p.loc == "A1":
            continue
        sym = syms[p.sym]
        for key, net in p.pins.items():
            num = sym.pin(key).number
            if net is None or (p.ref, num) in covered or f"{p.ref}.{num}" in W.DIRECT:
                continue
            errors.append(f"{p.ref}.{num} ({net}) has no wire run and no DIRECT reason")
    if errors:
        raise SystemExit("wire list does not match the schematic:\n  " + "\n  ".join(errors))
    return rows


def describe(ep, by_ref):
    if ep in W.BUS:
        return f"{ep} (interface board bus)"
    ref, pin = ep.split(".", 1)
    return f"{ref}.{pin}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    return "\n".join(out) + "\n"


def write_wire_list(out, rows, by_ref):
    with open(out / "WIRE_LIST.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Wire", "From", "To", "Net", "AWG", "Colour", "Protected by", "Route", "Note"])
        for r in rows:
            w.writerow([r["id"], r["a"], r["b"], r["net"], r["awg"], r["colour"], r["fuse"], r["route"], r["note"]])
    routes = {"adapter": "New lead at the battery", "box": "Inside the box", "harness": "Our new off-box harnesses (J9-J12)",
              "stock": "The car's own harness: listed so the circuit is complete, not touched"}
    txt = [HEAD, "# Wire list (v0.3)\n\n",
           "Every physical wire, generated from the schematic and checked against it: both ends of each run are on the "
           "same net, and every pin is reached by a wire, sits on the interface board A1, or is listed at the bottom with "
           "the reason. Label each wire at both ends with its W number (heat-shrink labels).\n\n",
           "Lengths are not given yet: they wait on the box and under-seat measurements (#18). Gauges are minimums; "
           "a heavier wire is always fine. A1:GND, A1:3V3 and A1:5V are the bus strips on the interface board.\n\n",
           "## Rules\n\n",
           "- **Every fuse protects the wire after it:** the wire is rated above the fuse. 10 AWG after F1 (40 A), 14 AWG after F2 (15 A), "
           "16 AWG after F6/F10 (10 A), 20-22 AWG after the 1-3 A fuses.\n",
           "- **The only unfused copper** is battery + to F1: keep it under 15 cm and away from metal edges.\n",
           "- **One ground star (TB1).** Battery −, every driver B−, the buck inputs and the A1 ground bus land there and nowhere else.\n",
           "- **Run each B+ beside its B−,** and each PWM/EN pair beside a GND wire, to keep loops small.\n",
           "- **Kill lines (yellow)** never share a connector pin with anything else and never get a pull-up.\n",
           "- **Motor leads** are protected by F1 and by the BTS7960's own current limit; 12 AWG is rated well above one motor's current.\n\n",
           "## Colour code\n\n", md_table(["Code", "Colour", "Use"], W.COLOURS), "\n"]
    for route, title in routes.items():
        rs = [r for r in rows if r["route"] == route]
        txt.append(f"## {title} ({len(rs)} wires)\n\n")
        txt.append(md_table(["Wire", "From", "To", "Net", "AWG", "Colour", "Protected by", "Note"],
                            [[r["id"], describe(r["a"], by_ref), describe(r["b"], by_ref), f"`{r['net']}`", r["awg"],
                              r["colour"], r["fuse"], r["note"]] for r in rs]))
        txt.append("\n")
    txt.append("## Pins with no wire of their own\n\n")
    txt.append(md_table(["Pin", "Why"], sorted(W.DIRECT.items())))
    (out / "WIRE_LIST.md").write_text("".join(txt))


def write_nets(out, nets, parts):
    by_ref = {p.ref: p for p in parts}
    rows = []
    for n in sorted(nets):
        g, c, fuse = W.net_class(n)
        sheets = sorted({by_ref[r].sheet for r, _, _ in nets[n]})
        pins = ", ".join(f"{r}.{num}" for r, num, _ in sorted(nets[n]) if not r.startswith("#"))
        rows.append([f"`{n}`", g, c, fuse, " ".join(sheets), pins])
    (out / "NETS.md").write_text(HEAD + "# Nets (v0.3)\n\n"
                                 "Every net in the schematic with its default wire gauge, colour and protecting fuse, the sheets it "
                                 "appears on and every pin on it. ESP32 signal names are the constants in include/pins.h.\n\n"
                                 + md_table(["Net", "AWG", "Colour", "Protected by", "Sheets", "Pins"], rows))


def write_connectors(out, parts, syms, rows):
    by_ref = {p.ref: p for p in parts}
    js = sorted([p for p in parts if p.ref.startswith("J")], key=lambda p: int(p.ref[1:]))
    txt = [HEAD, "# Connectors and pinouts (v0.3)\n\n",
           "Every plug on the box edge. **J1-J8 face the stock harness:** each must be the mate of the stock plug so the box "
           "swaps with the stock HY2005RX controller (plug and play). Their families, pin counts and pin order are **TBD** "
           "until the photos of the stock plugs (#17); the pin numbers below are our own until then. **J9-J12 are our own** "
           "sealed plugs for parts the stock car doesn't have.\n\n",
           "J8 and J9 each carry a supply line (12 V lights, 24 V coil chain) next to a 3.3 V input of U24. A pin-to-pin short "
           "there could reach the PCF8574, so keep those pins apart: in J9 the coil pair (1, 2) sits away from the sense pair "
           "(3, 4); J8's order waits on the stock plug.\n\n"]
    summary = []
    for j in js:
        facing = "stock harness (TBD #17)" if int(j.ref[1:]) <= 8 else "our harness"
        summary.append([j.ref, j.value, len(j.pins), facing, j.part, j.source])
    txt.append(md_table(["Ref", "Name", "Pins", "Faces", "Part", "Status"], summary))
    txt.append("\n")
    for j in js:
        txt.append(f"## {j.ref} {j.value}\n\n{j.part}. Status: {j.source}{' (' + j.issue + ')' if j.issue else ''}."
                   f"{' ' + j.note + '.' if j.note else ''}\n\n")
        prow = []
        for num in sorted(j.pins, key=int):
            net = j.pins[num]
            box = [r for r in rows if f"{j.ref}.{num}" in (r["a"], r["b"]) and r["route"] == "box"]
            car = [r for r in rows if f"{j.ref}.{num}" in (r["a"], r["b"]) and r["route"] != "box"]
            other = lambda r: r["b"] if r["a"] == f"{j.ref}.{num}" else r["a"]  # noqa: E731
            g, c, fuse = W.net_class(net)
            if box:
                g, c = box[0]["awg"], box[0]["colour"]
            prow.append([num, f"`{net}`", g, c, fuse,
                         ", ".join(f"{other(r)} ({r['id']})" for r in box) or "-",
                         ", ".join(f"{other(r)} ({r['id']})" for r in car) or "-"])
        txt.append(md_table(["Pin", "Net", "AWG", "Colour", "Protected by", "Box side", "Car side"], prow))
        txt.append("\n")
    (out / "CONNECTORS.md").write_text("".join(txt))


def write_bom(out, parts, vb_parts):
    groups = defaultdict(list)
    for p in parts:
        if p.ref.startswith("#") or not p.in_bom:
            continue
        groups[(p.part, p.value if p.sym.startswith("Device:") else "", p.source, order_line(p), p.loc.split(",")[0], p.dnp)].append(p)
    rows = []
    for (part, value, src, line, loc, _), ps in groups.items():
        refs = sorted((p.ref for p in ps), key=lambda r: (r.rstrip("0123456789"), int("".join(ch for ch in r if ch.isdigit()) or 0)))
        bits = (["Not fitted yet"] if any(p.dnp for p in ps) else []) + sorted({p.note for p in ps if p.note and len(ps) == 1})
        issue = ", ".join(sorted({p.issue for p in ps if p.issue}))
        if issue:
            bits.append(f"Issue {issue}")
        rows.append(dict(refs=" ".join(refs), qty=len(ps), part=part, loc=loc, src=src, line=line, note=". ".join(bits)))
    for ref, qty, part, loc, src, line, note in EXTRAS:
        rows.append(dict(refs=ref, qty=qty, part=part, loc=loc, src=src, line=line, note=note))
    order = {D.ORDER: 0, D.OWNED: 1, D.BUY: 2, D.TBD: 3, D.STOCK: 4}
    rows.sort(key=lambda r: (order.get(r["src"], 9), r["refs"]))
    with open(out / "BOM.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Refs", "Qty", "Part", "Where", "Status", "Order line (24 Oct)", "Note"])
        for r in rows:
            w.writerow([r["refs"], r["qty"], r["part"], r["loc"], r["src"], r["line"], r["note"]])
    titles = {D.ORDER: "In the 24 Oct order", D.OWNED: "Already owned", D.BUY: "Still to buy",
              D.TBD: "Waiting on a decision or the car photos", D.STOCK: "Stock car parts (kept, not bought)"}
    txt = [HEAD, "# Bill of materials (v0.3)\n\n",
           "Generated from the schematic fields (Part, Source, Location) and matched line by line to the AliExpress order "
           "of 24 Oct 2026 (shopping/2026-10-24-aliexpress-order.md). Variant A (4 + 1 IBT-2). Tools in the order (bench "
           "supply, clamp meter, USB-TTL, 18650 cells) are not part of the car and are left out.\n\n",
           "## Check when the order arrives\n\n",
           "- **470 µF capacitors (C111-C115):** the order line reads \"Electrolytic caps 10-25 V\". On a 24 V bus they must be "
           "**35 V or more** (50 V preferred). If the bag says 25 V, do not fit them; buy 470 µF 50 V low-ESR.\n",
           "- **ADS1115:** the order shows one line; the design needs 2 (U22, U23). Check the quantity.\n",
           "- **Blade fuse values:** the design uses 1, 2, 3, 10 and 15 A (F3-F10, F2). F8 is 1 A now (0.5 A in v0.2) and F10 "
           "is 10 A, so these five values cover every blade.\n",
           "- **K1 coil current:** measure it on the bench supply; over 0.6 A, F3 becomes 2 A.\n\n"]
    for src, title in titles.items():
        rs = [r for r in rows if r["src"] == src]
        if not rs:
            continue
        txt.append(f"## {title}\n\n")
        cols = ["Refs", "Qty", "Part", "Where", "Order line", "Note"] if src == D.ORDER else ["Refs", "Qty", "Part", "Where", "Note"]
        txt.append(md_table(cols, [[r["refs"], r["qty"], r["part"], r["loc"]] + ([r["line"]] if src == D.ORDER else []) + [r["note"]]
                                   for r in rs]))
        txt.append("\n")
    vb = defaultdict(list)
    for p in vb_parts:
        if not p.ref.startswith("#"):
            vb[(p.part, p.source)].append(p.ref)
    txt.append("## Variant B instead of the four drive IBT-2s\n\n"
               "If #32 picks variant B, these replace U10-U13 and C111-C114 (the steering IBT-2, U14, stays):\n\n")
    txt.append(md_table(["Refs", "Qty", "Part", "Status"], [[" ".join(r), len(r), k[0], k[1]] for k, r in vb.items()]))
    (out / "BOM.md").write_text("".join(txt))


def write_all(out, parts, nets, syms, gpio, vb_parts):
    rows = check_and_number_runs(parts, syms)
    by_ref = {p.ref: p for p in parts}
    write_wire_list(out, rows, by_ref)
    write_nets(out, nets, parts)
    write_connectors(out, parts, syms, rows)
    write_bom(out, parts, vb_parts)
    print(f"{len(rows)} wire runs checked")
