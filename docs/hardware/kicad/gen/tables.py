def endpoint_net(ep, by_ref, syms):
    if ep in W.BUS:
        return W.BUS[ep], None
    ref, pin = ep.split(".", 1)
    part = by_ref[ref]
    sym = syms[part.sym]
    p = sym.pin(pin)
    return part.pins[p.number], (ref, p.number)


def check_and_number_runs(parts, syms):
    by_ref = {p.ref: p for p in parts}
    errors, rows, covered = [], [], set()
    for i, r in enumerate(W.RUNS):
        try:
            na, pa = endpoint_net(r["a"], by_ref, syms)
            nb, pb = endpoint_net(r["b"], by_ref, syms)
        except KeyError as e:
            errors.append(f"run {r['a']} -> {r['b']}: {e}")
            continue
        if na != nb or na is None:
            errors.append(f"run {r['a']} -> {r['b']}: nets differ ({na} vs {nb})")
            continue
        covered |= {pa, pb} - {None}
        g, c, fuse = W.net_class(na)
        gauge = r["gauge"] or g
        ours = {"J9", "J10", "J11", "J12"}
        if (r["route"] == "harness" or {pa and pa[0], pb and pb[0]} & ours) and gauge > 20:
            gauge = 20  # Deutsch DT size-16 contacts take 20-14 AWG, and off-box wires need the strength
        if r["route"] in ("stock",):
            gauge, c = "stock", "stock"
        rows.append(dict(id=f"W{i + 1:03d}", a=r["a"], b=r["b"], net=na, awg=gauge, colour=r["colour"] or c,
                         fuse=fuse, route=r["route"], note=r["note"]))
    # coverage: every connected pin off the interface board needs a wire or a reason
    for p in parts:
        if p.ref.startswith("#") or p.loc == "A1":
            continue
        sym = syms[p.sym]
        for key, net in p.pins.items():
            num = sym.pin(key).number
            if net is None or (p.ref, num) in covered or f"{p.ref}.{num}" in W.DIRECT:
                continue
            errors.append(f"{p.ref}.{num} ({net}) has no wire run and no DIRECT reason")
    if errors:
        raise SystemExit("wire list does not match the schematic:\n  " + "\n  ".join(errors))
    return rows


def describe(ep, by_ref):
    if ep in W.BUS:
        return f"{ep} (interface board bus)"
    ref, pin = ep.split(".", 1)
    return f"{ref}.{pin}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    return "\n".join(out) + "\n"


