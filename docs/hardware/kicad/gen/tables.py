def order_line(p):
    if p.ref in ORDER_LINE:
        return ORDER_LINE[p.ref]
    if p.sym == "Device:R":
        return "Resistor kit, 60 values; metal film x100 (2 lines)"
    if p.sym == "Device:C":
        return "50 V monolithic caps x100 (2 lines)"
    if p.sym == "Device:C_Polarized":
        return "Electrolytic caps 10-25 V... (check the voltage)"
    if p.sym == "Device:D" and p.value == "1N4148":
        return "High-speed switching diodes x50"
    return ""


