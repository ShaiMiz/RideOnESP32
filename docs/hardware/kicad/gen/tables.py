def links_md(links):
    if not links:
        return "-"
    out = []
    for u in links.split(" / "):
        label, _, url = u.strip().rpartition("|")
        out.append(f"[{label or 'search'}]({url})")
    return ", ".join(out)


def ref_key(r):
    return (r.rstrip("0123456789"), int("".join(ch for ch in r if ch.isdigit()) or 0))


def ref_ranges(refs):
    """R101 R102 R103 R7 -> R101-R103, R7"""
    out = []
    for r in refs:
        pre, num = ref_key(r)
        if out and out[-1][0] == pre and out[-1][2] == num - 1:
            out[-1][2] = num
        else:
            out.append([pre, num, num])
    return ", ".join(f"{p}{a}" if a == b else f"{p}{a}{'-' if b > a + 1 else ', '}{p}{b}" for p, a, b in out)


def where(loc):
    """The place part of a Location field: 'box, on U10 B+/B-' -> 'box'; a comma inside brackets stays."""
    head = loc.split(",")[0]
    return head if head.count("(") == head.count(")") else loc.split(")")[0] + ")"


STATUS_ORDER = [D.OWNED, D.ORDER, D.BUY, D.TBD, D.STOCK]


def bom_rows(parts):
    """One row per distinct part: refs that use the same part share a line, whatever their position or status."""
    groups = defaultdict(list)
    for p in parts:
        if p.ref.startswith("#") or not p.in_bom:
            continue
        name, use = BOM_NAME.get(p.ref, (POSITION.sub("", p.part), ""))
        groups[name].append((p, use))
    rows = []
    for name, pus in groups.items():
        pus.sort(key=lambda pu: ref_key(pu[0].ref))
        ps = [p for p, _ in pus]
        notes = []
        for p, use in pus:
            bits = ([use] if use else []) + (["not fitted yet"] if p.dnp else []) + ([p.note] if p.note else [])
            bits += [f"Issue {p.issue}"] if p.issue else []
            notes.append((p.ref, ". ".join(bits)))
        by_note = defaultdict(list)
        for r, n in notes:
            by_note[n].append(r)
        if len(by_note) == 1:
            note = notes[0][1]
        else:
            note = "; ".join(f"{ref_ranges(rs)}: {n}" for n, rs in by_note.items() if n)
        spec = next((BUY_LINKS[p.ref] for p in ps if p.ref in BUY_LINKS and p.source == D.BUY), None)
        if spec:
            note = ". ".join(x for x in (note, f"Spec: {spec[0]}") if x)
        counts = Counter(p.source for p in ps)
        lines = sorted({l for p in ps for l in order_lines(p)}, key=lambda l: int(LINE_NO[l][1:]))
        rows.append(dict(cat=category(ps[0].ref, ps[0].source), refs=" ".join(p.ref for p in ps), qty=len(ps), item=name,
                         mfr=next((mfr(p) for p in ps if mfr(p)), ""), loc=", ".join(dict.fromkeys(where(p.loc) for p in ps)),
                         counts=counts, lines=lines, premium="", link=spec[1] if spec else "", note=note))
    for ref, qty, item, mk, loc, src, lines, note in EXTRAS:
        rows.append(dict(cat=category(ref, src) if ref else "Wiring", refs=ref, qty=qty, item=item, mfr=mk, loc=loc,
                         counts=Counter({src: qty}), lines=lines, premium="", link=EXTRA_LINKS.get(item, "") if src == D.BUY else "",
                         note=note))
    for qty, item, mk, note in SPARES:
        rows.append(dict(cat="Spare", refs="", qty=qty, item=item, mfr=mk, loc="-", counts=Counter({D.OWNED: qty}), lines=[],
                         premium="", link="", note=note))
    for t in TOOLS:
        rows.append(dict(cat=t["cat"], refs="", qty=t["qty"], item=t["item"], mfr=t["mfr"], loc="bench",
                         counts=Counter({t["src"]: t["qty"] or 1}), lines=t["lines"], premium=t["premium"], link=t["link"],
                         note=t["note"]))
    for r in rows:
        r["status"] = min(r["counts"], key=STATUS_ORDER.index) if len(r["counts"]) == 1 else ", ".join(
            f"{s} {r['counts'][s]}" for s in STATUS_ORDER if s in r["counts"])
        r["first"] = min(r["counts"], key=STATUS_ORDER.index)
        r["order"] = ", ".join(LINE_NO[l] for l in r["lines"])
        r["supplier"] = ("AliExpress, 24 Oct order" if r["lines"] else "Stock car" if r["first"] == D.STOCK else
                         "AliExpress" if r["link"] else "Owned" if r["first"] == D.OWNED else "")
    rows.sort(key=lambda r: (CATEGORY_ORDER.index(r["cat"]), STATUS_ORDER.index(r["first"]),
                             ref_key(r["refs"].split()[0]) if r["refs"] else ("~", 0), r["item"]))
    for i, r in enumerate(rows):
        r["no"] = i + 1
    return rows


